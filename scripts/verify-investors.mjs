import { chromium, devices } from "playwright";
import assert from "node:assert/strict";
import path from "node:path";

const base = process.env.TEST_URL || "http://127.0.0.1:3100";
if (!/^http:\/\/(127\.0\.0\.1|localhost):3100$/.test(base)) throw new Error("Use the isolated test server on port 3100.");
const browser = await chromium.launch({ headless: true, channel: process.env.TEST_BROWSER_CHANNEL || (process.platform === "win32" ? "msedge" : undefined) });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
page.setDefaultTimeout(20000);
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
const read = (url) => page.evaluate(async (url) => { const r = await fetch(url); if (!r.ok) throw new Error(`HTTP ${r.status}`); return r.json(); }, url);
const respond = (suffix, method) => page.waitForResponse((r) => r.url().endsWith(suffix) && r.request().method() === method);
try {
  await page.goto(base + "/investors");
  await page.getByRole("heading", { name: "Investors", exact: true }).waitFor();
  const status = await read("/api/integrations/status");
  assert.ok(status.obsidian.dir?.endsWith("realtorpro-browser-vault"), "Refusing to use a personal vault");
  assert.equal(status.claude.configured, false, "No real Claude connection allowed");
  const existing = await read("/api/contacts?limit=1000");
  assert.ok(existing.items.every((c) => ["browser-test@example.com", "investor-browser@example.com"].includes(c.email)), "Refusing to use personal records");
  for (const c of existing.items.filter((c) => c.email === "investor-browser@example.com")) {
    await page.evaluate(async (id) => { const r = await fetch(`/api/contacts/${id}`, { method: "DELETE" }); if (!r.ok) throw new Error("Test fixture cleanup failed"); }, c.id);
  }
  assert.equal((await read("/api/investors")).count, 0);
  await page.getByText("Build your investor network", { exact: true }).waitFor();
  await page.getByRole("button", { name: "+ New investor contact", exact: true }).first().click();
  await page.getByLabel("First name").fill("Investor Browser");
  await page.getByLabel("Last name").fill("Test");
  await page.getByLabel("Email", { exact: true }).fill("investor-browser@example.com");
  const createdContact = respond("/api/contacts", "POST");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  const contactResponse = await createdContact;
  assert.equal(contactResponse.status(), 201);
  const contact = (await contactResponse.json()).item;
  await page.getByRole("heading", { name: "New Investor", exact: true }).waitFor();
  await page.waitForFunction((id) => document.querySelector("#f-investors-contactId")?.value === id, contact.id);
  assert.equal(await page.locator("#f-investors-contactId").inputValue(), contact.id);
  await page.getByLabel("Primary strategy", { exact: true }).selectOption("buy_and_hold");
  await page.getByLabel("Target markets", { exact: true }).fill("Test Market");
  await page.getByLabel("Property types", { exact: true }).pressSequentially("Duplex, Multifamily");
  await page.getByLabel("Purchase budget from", { exact: true }).fill("400000");
  await page.getByLabel("Purchase budget to", { exact: true }).fill("100");
  let saved = respond("/api/investors", "POST");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  assert.equal((await saved).status(), 422);
  await page.getByRole("alert").filter({ hasText: "Maximum budget" }).waitFor();
  assert.equal((await read("/api/investors")).count, 0);
  await page.getByLabel("Purchase budget to", { exact: true }).fill("900000");
  await page.getByLabel("Available capital (self-reported)", { exact: true }).fill("200000");
  await page.getByLabel("Target cap rate (%)", { exact: true }).fill("6");
  await page.getByLabel("Must-haves", { exact: true }).fill("Property manager");
  saved = respond("/api/investors", "POST");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  const savedResponse = await saved;
  assert.equal(savedResponse.status(), 201);
  const investor = (await savedResponse.json()).item;
  assert.deepEqual(investor.propertyTypes, ["Duplex", "Multifamily"], "Typing comma-separated criteria must preserve separate values");
  await page.getByRole("link", { name: "Investor Browser Test", exact: true }).waitFor();
  await page.reload();
  await page.getByText("$200,000", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  await page.locator("#f-investors-status").selectOption("paused");
  saved = respond(`/api/investors/${investor.id}`, "PATCH");
  await page.getByRole("button", { name: "Save changes", exact: true }).click();
  assert.equal((await saved).status(), 200);
  await page.getByLabel("Investor status", { exact: true }).selectOption("active");
  await page.getByText("No matching investors", { exact: true }).waitFor();
  await page.getByLabel("Investor status", { exact: true }).selectOption("all");
  await page.getByRole("button", { name: "+ Task", exact: true }).click();
  await page.getByLabel("Task", { exact: false }).first().fill("Review investor criteria");
  const taskCreated = respond("/api/tasks", "POST");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  const taskResponse = await taskCreated;
  assert.equal(taskResponse.status(), 201);
  const task = (await taskResponse.json()).item;
  assert.equal((await read(`/api/tasks?contactId=${contact.id}`)).items[0].title, "Review investor criteria");

  // Deterministic extraction fixture: exercise the real review boundary without a paid AI call.
  const proposal = await page.evaluate(async (contact) => {
    const r = await fetch("/api/import/preview", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ source: "Investor browser verification", bundle: { contacts: [{ name: `${contact.firstName} ${contact.lastName}`, email: contact.email, nextFollowUpAt: "2026-10-01", investor: { status: "active", timeline: "Next six months" } }] } }) });
    if (!r.ok) throw new Error(`Preview failed: ${r.status}`); return r.json();
  }, contact);
  assert.equal((await read(`/api/investors/${investor.id}`)).item.status, "paused");
  await page.goto(base + "/reviews");
  const reviewCard = page.locator(".card").filter({ hasText: proposal.reviewId });
  const approved = respond("/api/import/apply", "POST");
  await reviewCard.getByRole("button", { name: "Approve these changes", exact: true }).click();
  assert.equal((await approved).status(), 200);
  assert.equal((await read("/api/investors")).count, 1);
  assert.equal((await read(`/api/investors/${investor.id}`)).item.status, "active");
  await page.goto(base + "/investors");
  await page.getByText("Next six months", { exact: true }).waitFor();
  await page.screenshot({ path: path.resolve("../../outputs/realtorpro-investors-desktop.png"), fullPage: true, animations: "disabled" });
  await page.getByRole("link", { name: "Follow-up", exact: true }).click();
  await page.getByText("Investor profile", { exact: true }).waitFor();
  await page.getByRole("link", { name: "Open →", exact: true }).click();
  await page.getByRole("link", { name: "Show all investors", exact: true }).click();
  await page.getByRole("link", { name: "Investor Browser Test", exact: true }).waitFor();
  console.log("PASS create contact → profile; invalid budget; edit/reload/filter; linked task; preview → approval; contact navigation");

  const mobile = await browser.newContext({ ...devices["iPhone 13"] });
  const phone = await mobile.newPage();
  phone.on("pageerror", (e) => errors.push(e.message));
  await phone.goto(base + "/investors");
  await phone.getByRole("link", { name: "Investor Browser Test", exact: true }).waitFor();
  assert.ok(await phone.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1), "No horizontal mobile overflow");
  await phone.screenshot({ path: path.resolve("../../outputs/realtorpro-investors-mobile.png"), fullPage: true, animations: "disabled" });
  await mobile.close();

  await page.getByRole("button", { name: "Delete", exact: true }).click();
  const deleted = respond(`/api/investors/${investor.id}`, "DELETE");
  await page.getByRole("button", { name: "Delete", exact: true }).last().click();
  assert.equal((await deleted).status(), 200);
  assert.equal((await read(`/api/contacts/${contact.id}`)).item.email, contact.email);
  await page.evaluate(async (id) => { const r = await fetch(`/api/tasks/${id}`, { method: "DELETE" }); if (!r.ok) throw new Error("Test task cleanup failed"); }, task.id);
  await page.evaluate(async (id) => { const r = await fetch(`/api/contacts/${id}`, { method: "DELETE" }); if (!r.ok) throw new Error("Test contact cleanup failed"); }, contact.id);
  assert.deepEqual(errors, [], "No browser JavaScript exceptions");
  console.log("PASS mobile layout; profile deletion preserves contact; test contact cleaned up; no browser exceptions");
} finally { await browser.close(); }
